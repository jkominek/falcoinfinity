	out (08bh),a
	in a,(08bh)
	and 0f1h
	ret	
test_screen_ram:
	; C=52 selects the CPU-visible screen-RAM page; D and E are the
	; candidate page values supplied by detect_board_memory_and_asic.
	ld c,052h
	out (c),d
	ld (hl),055h
	out (c),e
	ld (hl),0aah
	out (c),d
	ld a,(hl)	
	cp 055h
	jr nz,$+7
	out (c),e
	ld a,(hl)	
	cp 0aah
	ld a,000h
	ret	

